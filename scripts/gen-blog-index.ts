// Regenerates src/lib/blog-index.ts: a small summary of every blog post (no body content).
// Run: node --import tsx scripts/gen-blog-index.ts
import { writeFileSync } from "node:fs";
import { ALL_BLOG_POSTS } from "../src/lib/blog-data.ts";

const summaries = ALL_BLOG_POSTS.map((p) => ({
  slug: p.slug,
  h1: p.h1,
  excerpt: p.excerpt,
  featuredImage: p.featuredImage,
  imageAlt: p.imageAlt,
  category: p.category,
  keywords: p.keywords,
}));

const out = `// GENERATED by scripts/gen-blog-index.ts. Do not edit by hand.
// Lightweight summaries used for related-post cards, so pages do not load the full blog library.
export type BlogPostSummary = {
  slug: string;
  h1: string;
  excerpt: string;
  featuredImage: string;
  imageAlt?: string;
  category: string;
  keywords: string[];
};

export const BLOG_INDEX: BlogPostSummary[] = ${JSON.stringify(summaries, null, 1)};
`;
writeFileSync("src/lib/blog-index.ts", out);
console.log("Wrote", summaries.length, "posts,", out.length, "bytes");
