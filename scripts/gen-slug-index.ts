/**
 * Regenerates src/lib/seo-pages/slug-index.ts from the real page groups.
 * Run after adding or moving a legacy SEO page file:
 *   node --import tsx scripts/gen-slug-index.ts
 * The slug index must list every slug exactly once and point it at the group that holds the
 * page the site renders today (the LAST occurrence in ALL_SEO_PAGES wins, like the old lookup map).
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ALL_SEO_PAGES } from "../src/lib/seo-pages/registry.ts";
import { GROUP_FILES } from "../src/lib/seo-pages/group-files.ts";

const pageGroup = new Map<object, string>();
for (const [id, pages] of Object.entries(GROUP_FILES)) for (const p of pages) pageGroup.set(p, id);

const slugGroup = new Map<string, string>();
const extraCopies: string[] = [];
const missing: string[] = [];
for (const page of ALL_SEO_PAGES) {
  const group = pageGroup.get(page);
  if (!group) {
    missing.push(page.slug);
    continue;
  }
  if (slugGroup.has(page.slug)) extraCopies.push(page.slug);
  slugGroup.set(page.slug, group);
}
if (missing.length > 0) throw new Error(`Pages not in any group: ${missing.join(", ")}`);

const ids = Object.keys(GROUP_FILES);
const lines = [
  "// GENERATED by scripts/gen-slug-index.ts. Do not edit by hand.",
  "// Lightweight slug -> group map so the main bundle never loads page content.",
  `export const GROUP_IDS = ${JSON.stringify(ids)} as const;`,
  "export type SeoGroupId = (typeof GROUP_IDS)[number];",
  "",
  "export const SLUG_GROUP: Readonly<Record<string, SeoGroupId>> = {",
  ...[...slugGroup].map(([slug, group]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(group)},`),
  "};",
  "",
  "/** True when a legacy SEO page exists at this slug (no leading slash). */",
  "export const hasSeoPage = (slug: string): boolean => Object.hasOwn(SLUG_GROUP, slug);",
  "",
  "/**",
  " * Slugs that the registry lists more than once (one entry per extra copy). area-links counts them",
  " * when rotating same-city pills, so they are kept to leave those pills exactly as they were.",
  " */",
  `export const EXTRA_SLUG_COPIES: readonly string[] = ${JSON.stringify(extraCopies)};`,
  "",
  "/** All legacy SEO slugs, in registry order. */",
  "export const allSeoSlugs = (): string[] => Object.keys(SLUG_GROUP);",
  "",
];
writeFileSync(resolve(import.meta.dirname, "../src/lib/seo-pages/slug-index.ts"), lines.join("\n"));
console.log(`Wrote ${slugGroup.size} slugs in ${ids.length} groups`);
