// ─── Types ───────────────────────────────────────────────────────────────────

export type BuildingType =
  | "it-hub"
  | "corporate-offices"
  | "business-centre"
  | "industrial-area"
  | "coworking-cluster";

export type CommercialMetrics = {
  /** Office/business establishment density 1–10 */
  officeDensity: number;
  /** Estimated organic search demand 1–10 */
  searchDemand: number;
  /** Commercial/strategic importance 1–10 */
  businessImportance: number;
  /** Competitive landscape 1–10 (10 = most competitive) */
  competition: number;
  /** Transport and accessibility 1–10 */
  accessibility: number;
};

/** commercialScore is DERIVED (sum of metrics), never stored */
export function computeCommercialScore(metrics: CommercialMetrics): number {
  return (
    metrics.officeDensity +
    metrics.searchDemand +
    metrics.businessImportance +
    metrics.competition +
    metrics.accessibility
  );
}

